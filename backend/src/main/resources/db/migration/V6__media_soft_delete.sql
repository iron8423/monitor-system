-- =====================================================================
-- V6 media 支持软删除（契约 §7 新增 DELETE /api/v1/media/{mediaId}）
--
-- 背景：媒体模块此前只有上传 / 列表 / 内容三条端点，**没有任何删除手段**。
--   media 表没有 deleted 列，所以「删」连表达都表达不出来。两个后果：
--     ① 验收套件 06-media.sh 每跑一轮就往库里留一张 1×1 测试图，回收不了；
--     ② 运维误传的现场照片，界面上没有任何手段可以撤。
--
-- 为什么是**软删**而不是物理删（用户定案）：
--   与 monitor_point / device 的既有口径一致——本仓所有档案类实体都走
--   `deleted` 逻辑删除，只有 alarm_rule 是物理删（那张表当初没建 deleted 列）。
--   一致的语义比「省一点磁盘」重要：软删可审计、可回溯，误删不至于不可挽回。
--
-- 代价说清楚：**盘上的文件不删**（卷只增不减）。删的只是库里的可见性，
-- 文件仍留在 <uploadDir>/<pointCode>/ 下。这是刻意的——物理删文件是不可逆的，
-- 而软删的全部价值就在于可挽回。需要真正回收磁盘时，另配离线清理策略，
-- 按「deleted=1 且超过保留期」挑文件删，而不是让接口顺手删掉。
--
-- 列定义与 V1 里 monitor_point 等的 `deleted INT NOT NULL DEFAULT 0` 完全一致，
-- 存量行因此天然是「未删除」。MyBatis-Plus 的全局 logic-delete-field=deleted
-- （见 application.yml）会自动接管，所有既有查询自动带上 `AND deleted = 0`。
-- =====================================================================

ALTER TABLE media ADD COLUMN deleted INT NOT NULL DEFAULT 0;
