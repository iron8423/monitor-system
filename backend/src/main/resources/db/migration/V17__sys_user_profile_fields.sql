-- V17 用户资料字段（个人中心）
--
-- 背景：个人中心要展示「公司 / 岗位 / 联系电话 / 邮箱」，而 sys_user 此前只有
-- 账号、口令、姓名、角色、组织、启用状态——一句话，它只有「登录要用的」，
-- 没有「给人看的」。这里补上后三项。
--
-- 为什么「公司」不在这里加列：账号已经挂在 organization_id 上，组织名就是公司名。
-- 再存一份字符串会立刻产生两个事实源——组织改名之后，个人中心还念着旧名字，
-- 而且没有任何地方能发现这件事（同 V15 对 valid_to 的判断：一个语义只用一个列）。
--
-- 为什么都允许为空：库里已经躺着行（演示账号，以及将来管理员建的号），
-- 这些是「有则更好」的资料，不是登录或鉴权的前提。给一个 NOT NULL 默认值，
-- 只会往库里灌一批看起来像真数据的占位串。
--
-- 为什么**不**回填：迁移不该编造联系方式。演示账号那几行由 DataInitializer
-- 在字段为空时补上（见其 javadoc），真实账号留空、等管理员录入。
ALTER TABLE sys_user
    ADD COLUMN phone VARCHAR(32);

ALTER TABLE sys_user
    ADD COLUMN email VARCHAR(128);

ALTER TABLE sys_user
    ADD COLUMN job_title VARCHAR(64);
