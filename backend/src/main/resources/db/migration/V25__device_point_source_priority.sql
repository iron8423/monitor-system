-- =====================================================================
-- V25 多源权威：设备-测点绑定的「来源优先级」（复查清单 P1-2）
--
-- 要解决的问题：一个测点可以被**多台设备**观测（device_point 上只有
-- UNIQUE(device_id, point_id)，没有「一台设备只能看一个点」之类的约束），
-- 而平台取「当前值」的判据一直是 collect_time DESC, id DESC —— **与来源无关**。
-- 于是两台雷达看同一个点时，谁的值算"当前值"取决于谁的消息晚到几毫秒：
-- 采样更慢、或链路更慢的那台会持续盖掉快的那台，而界面上看不出来（只有一个数）。
--
-- 加一列 source_priority：
--   数值**越小越优先**（与路由 metric 同向，读代码时不容易反）；
--   默认 100 = 「未特别指定」。所有来源都在默认值上时，取值仍然完全按时间先后——
--   也就是**既有行为一字不变**（这是刻意的：存量数据与既有验收不该因为这次改动漂移）；
--   管理员把某台设成 10 之后，它就成为"权威来源"：只要它有数据，就取它的值，
--   哪怕另一台的时间戳更新。
--
-- 为什么是"优先级 + 时间"而不是布尔主备：
--   主备二值在只有两台时够用，但现场常见"雷达 + 全站仪 + 人工复测"三源，
--   而且换主来源时布尔要动两行（先把 A 置否、再把 B 置是），期间存在"两个主"的窗口。
--   整数排序天然表达任意多档，改一行即完成切换。
--
-- 为什么不在这里加 CHECK 约束：允许的取值范围是 1..999（见
-- DeviceController#updateSourcePriority 的校验），但 CHECK 会让"以后想放宽"变成一次迁移；
-- 而这一列的语义不依赖取值边界，越界只会导致排序不合预期、不会破坏数据。
--
-- 未绑定来源（例如设备直接给某点上报但没建绑定）**不写行**，取值时按默认 100 参与——
-- 所以"没绑定"不会让数据消失，只是不享有更高的权威。这一点在
-- MeasurementQueryService#resolveLatestRow 的注释里有完整说明。
-- =====================================================================

ALTER TABLE device_point ADD COLUMN source_priority INT NOT NULL DEFAULT 100;

-- 取值路径是「按测点找出各来源、按优先级排序」，这个索引正好覆盖
CREATE INDEX idx_device_point_source ON device_point (point_id, source_priority);
